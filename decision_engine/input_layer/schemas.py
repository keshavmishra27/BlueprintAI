class UnvalidatedArchitectureHypothesis(BaseModel):
    """
    Represents an architecture hypothesis generated by an LLM or external source.
    This is intentionally NOT an ArchitectureNode, enforcing the semantic boundary 
    that it is unvalidated and lacks authority.
    """
    class Config:
        extra = "allow"
        
    inputs: List[str] = []
    processing: List[str] = []
    decision: List[str] = []
    output: List[str] = []
    
    capabilities: List[CapabilityProposal] = []
    semantic_dependencies: List[str] = []
    data_required: List[str] = []
    resources_required: List[str] = []
    constraints: List[SemanticClaim] = []
    architectural_decisions: Dict[str, str] = {}
    
    id: str = ""
    parent_id: Optional[str] = None
    generation_reason: Optional[str] = None
    source: str = "llm_generated"
    hypothesis: bool = True
    path_cost: float = 10.0
    path_score: float = 50.0
    operational_complexity: float = 0.0
    provenance: Dict[str, Any] = {}

    def get_signature(self) -> str:
        """
        Returns a canonical signature to test diversity of hypotheses.
        """
        import hashlib
        import json
        canonical_dict = {
            "inputs": sorted(self.inputs),
            "processing": sorted(self.processing),
            "decision": sorted(self.decision),
            "output": sorted(self.output),
            "capabilities": sorted([c.model_dump() for c in self.capabilities], key=lambda x: x["name"]),
            "semantic_dependencies": sorted(self.semantic_dependencies),
            "data_required": sorted(self.data_required),
            "resources_required": sorted(self.resources_required),
            "constraints": sorted([c.model_dump() for c in self.constraints], key=lambda x: x["claim_id"]),
            "architectural_decisions": {k: self.architectural_decisions[k] for k in sorted(self.architectural_decisions.keys())}
        }
        canonical_json = json.dumps(canonical_dict, sort_keys=True)
        return hashlib.sha256(canonical_json.encode('utf-8')).hexdigest()

class ArchitectureNode(BaseModel):
    inputs: List[str] = []
    processing: List[str] = []
    decision: List[str] = []
    output: List[str] = []
    
    capabilities: List[CapabilityNode] = []
    semantic_dependencies: List[str] = []
    data_required: List[str] = []
    resources_required: List[str] = []
    constraints: List[SemanticClaim] = []
    evidence_provenance: List[str] = []
    historical_decisions: List[TransferredDecision] = []
    architectural_decisions: Dict[str, str] = {}

    candidate_status: Optional[CandidateStatus] = CandidateStatus.FEASIBLE
    performance: Optional[Dict[str, Any]] = None
    cost: Optional[Dict[str, Any]] = None
    timeline: Optional[Dict[str, Any]] = None

    def get_fingerprint(self) -> str:
        """
        Returns a canonical SHA256 fingerprint of the architecture.
        This provides a deterministic tie-breaker for optimization.
        """
        import hashlib
        import json
        
        canonical_dict = {
            "inputs": sorted(self.inputs),
            "processing": sorted(self.processing),
            "decision": sorted(self.decision),
            "output": sorted(self.output),
            "capabilities": sorted([c.model_dump() for c in self.capabilities], key=lambda x: x["name"]),
            "semantic_dependencies": sorted(self.semantic_dependencies),
            "data_required": sorted(self.data_required),
            "resources_required": sorted(self.resources_required),
            "constraints": sorted([c.model_dump() for c in self.constraints], key=lambda x: x["claim_id"]),
            "architectural_decisions": {k: self.architectural_decisions[k] for k in sorted(self.architectural_decisions.keys())}
        }
        
        canonical_json = json.dumps(canonical_dict, sort_keys=True)
        return hashlib.sha256(canonical_json.encode('utf-8')).hexdigest()

    def get_authority_fingerprint(self) -> str:
        """
        Returns a canonical SHA256 fingerprint of ONLY the authority-bearing fields.
        This provides a secure binding between an ExecutionCapability and the specific
        architectural state it authorizes, while allowing descriptive metadata to change.
        """
        import hashlib
        import json
        import copy
        
        def canonicalize_claims(claims):
            return sorted([c.model_dump() for c in claims], key=lambda x: x["claim_id"])
            
        def canonicalize_capability(cap):
            d = cap.model_dump()
            d["functional_properties"] = canonicalize_claims(cap.functional_properties)
            d["constraints"] = canonicalize_claims(cap.constraints)
            return d
            
        canonical_dict = {
            "processing": list(self.processing), # Preserves order, as processing is a pipeline
            "capabilities": sorted([canonicalize_capability(c) for c in self.capabilities], key=lambda x: x.get("capability_id", x.get("name", ""))),
            "constraints": canonicalize_claims(self.constraints)
        }
        
        canonical_json = json.dumps(canonical_dict, sort_keys=True)
        return hashlib.sha256(canonical_json.encode('utf-8')).hexdigest()

